def _plugin_source(token: str) -> str:
    return (
        PLUGIN_SOURCE.replace("__KOVA_TOKEN__", token)
        .replace("__KOVA_PLUGIN_VERSION__", PLUGIN_VERSION)
        .replace("__KOVA_PROTOCOL__", str(PROTOCOL_VERSION))
    )


def _valid_name(value: Any) -> bool:
    if not isinstance(value, str):
        return False
    value = value.strip()
    if not value or len(value) > 80:
        return False
    return not any(char in value for char in './\\')


def _valid_path(value: Any) -> bool:
    if value is None or value == "":
        return True
    if not isinstance(value, str):
        return False
    return all(_valid_name(part) for part in value.split(".") if part)


def _numeric_list(value: Any, size: int) -> bool:
    if not isinstance(value, list) or len(value) != size:
        return False
    return all(isinstance(item, (int, float)) for item in value)


def _validate_command(command: dict[str, Any]) -> None:
    kind = str(command.get("type") or "")
    if kind not in COMMANDS:
        raise ValueError("unknown Roblox command")
    if kind == "batch":
        items = command.get("commands")
        if not isinstance(items, list) or not items or len(items) > MAX_BATCH:
            raise ValueError("batch must contain 1..100 commands")
        for item in items:
            if not isinstance(item, dict) or item.get("type") == "batch":
                raise ValueError("invalid batch item")
            _validate_command(item)
        return
    service = command.get("service")
    if service is not None and service not in SERVICES:
        raise ValueError(f"unknown Roblox service: {service}")
    if not _valid_path(command.get("path")):
        raise ValueError("invalid Roblox path")
    name = command.get("name")
    if name is not None and not _valid_name(name):
        raise ValueError("invalid Roblox instance name")
    if kind in {
        "create_script",
        "create_folder",
        "create_part",
        "create_mesh_part",
        "upload_mesh",
        "set_source",
        "set_properties",
        "delete",
    }:
        if kind != "upload_mesh" and not command.get("path") and kind not in {
            "create_script",
            "create_folder",
            "create_part",
            "create_mesh_part",
        }:
            raise ValueError("path is required")
    if kind in {"create_script", "create_folder"} and not command.get("service"):
        raise ValueError("service is required")
    if kind == "create_script":
        if command.get("script_type", "Script") not in {"Script", "LocalScript", "ModuleScript"}:
            raise ValueError("invalid script_type")
        source = command.get("source", "")
        if not isinstance(source, str) or len(source) > MAX_SOURCE:
            raise ValueError("source is too large")
    if kind == "set_source":
        source = command.get("source", "")
        if not isinstance(source, str) or len(source) > MAX_SOURCE:
            raise ValueError("source is too large")
    if kind in {"create_mesh_part", "upload_mesh"}:
        if kind == "create_mesh_part":
            asset_id = str(command.get("asset_id") or "")
            if not re.fullmatch(r"\d+", asset_id):
                raise ValueError("asset_id must be numeric")
            texture_id = str(command.get("texture_id") or "")
            if texture_id and not re.fullmatch(r"\d+", texture_id):
                raise ValueError("texture_id must be numeric")
        if kind == "upload_mesh":
            positions = command.get("positions")
            triangles = command.get("triangles")
            if not isinstance(positions, list) or not positions:
                raise ValueError("positions are required")
            if len(positions) > MAX_MESH_VERTICES:
                raise ValueError("too many mesh vertices")
            if not all(_numeric_list(item, 3) for item in positions):
                raise ValueError("each position must be [x, y, z]")
            if not isinstance(triangles, list) or not triangles:
                raise ValueError("triangles are required")
            if len(triangles) > MAX_MESH_TRIANGLES:
                raise ValueError("too many mesh triangles")
            for triangle in triangles:
                if not isinstance(triangle, list) or len(triangle) != 3:
                    raise ValueError("each triangle must have 3 indices")
                for index in triangle:
                    if not isinstance(index, int) or index < 1 or index > len(positions):
                        raise ValueError("triangle index out of range")
            for key, size in (("normals", 3), ("uvs", 2), ("colors", 3)):
                values = command.get(key)
                if values is None:
                    continue
                if not isinstance(values, list) or len(values) != len(positions):
                    raise ValueError(f"{key} must match positions length")
                if not all(_numeric_list(item, size) for item in values):
                    raise ValueError(f"invalid {key} entry")
    if kind == "set_properties":
        properties = command.get("properties")
        if not isinstance(properties, dict) or not properties:
            raise ValueError("properties are required")
        unknown = set(properties) - PROPERTY_WHITELIST
        if unknown:
            raise ValueError(f"property is not allowed: {sorted(unknown)[0]}")
    if kind == "playtest":
        duration = command.get("duration", 6)
        if not isinstance(duration, (int, float)) or not 2 <= duration <= 60:
            raise ValueError("duration must be 2..60 seconds")
    if kind == "get_tree":
        depth = command.get("depth", 2)
        if not isinstance(depth, int) or not 1 <= depth <= 4:
            raise ValueError("depth must be 1..4")


def _studio_roots() -> list[Path]:
    if os.name == "nt":
        local = Path(os.environ.get("LOCALAPPDATA") or Path.home() / "AppData" / "Local")
        return [
            local / "Roblox" / "Versions",
            Path("C:/Program Files/Roblox/Versions"),
            Path("C:/Program Files (x86)/Roblox/Versions"),
        ]
    if sys.platform == "darwin":
        return [
            Path("/Applications"),
            Path.home() / "Applications",
            Path.home() / "Applications" / "Roblox",
        ]
    return []


def find_studio() -> Path | None:
    override = os.environ.get("KOVA_ROBLOX_STUDIO", "").strip()
    if override:
        path = Path(override)
        return path if path.is_file() else None
    found: list[Path] = []
    if sys.platform == "darwin" and os.name != "nt":
        for root in _studio_roots():
            for candidate in (
                root / "RobloxStudio.app" / "Contents" / "MacOS" / "RobloxStudio",
                root / "Roblox" / "RobloxStudio.app" / "Contents" / "MacOS" / "RobloxStudio",
            ):
                if candidate.is_file():
                    found.append(candidate)
    else:
        for root in _studio_roots():
            if not root.is_dir():
                continue
            for candidate in root.glob("*/RobloxStudioBeta.exe"):
                if candidate.is_file():
                    found.append(candidate)
    if not found:
        return None
    found.sort(key=lambda item: item.stat().st_mtime, reverse=True)
    return found[0]


def plugin_path() -> Path:
    if os.name == "nt":
        local = Path(os.environ.get("LOCALAPPDATA") or Path.home() / "AppData" / "Local")
        return local / "Roblox" / "Plugins" / "KovaBridge.lua"
    if sys.platform == "darwin":
        return Path.home() / "Documents" / "Roblox" / "Plugins" / "KovaBridge.lua"
    base = os.environ.get("XDG_DATA_HOME")
    root = Path(base) if base else Path.home() / ".local" / "share"
    return root / "Roblox" / "Plugins" / "KovaBridge.lua"


class RobloxBridge:
    def __init__(self) -> None:
        self._lock = Lock()
        self._queue: deque[dict[str, Any]] = deque(maxlen=MAX_BATCH)
        self._pending: dict[str, dict[str, Any]] = {}
        self._results: OrderedDict[str, dict[str, Any]] = OrderedDict()
        self._last_seen = 0.0
        self._plugin_version = ""
        self._plugin_protocol = 0
        self._last_error = ""
        self._events: deque[dict[str, Any]] = deque(maxlen=50)
        self._token = ""

    def reset(self) -> None:
        with self._lock:
            self._queue.clear()
            self._pending.clear()
            self._results.clear()
            self._events.clear()
            self._last_seen = 0.0
            self._plugin_version = ""
            self._plugin_protocol = 0
            self._last_error = ""
            self._token = ""

    def _token_file(self) -> Path:
        return app_data_dir() / "roblox-bridge.json"

    def _load_token(self) -> str:
        override = os.environ.get("KOVA_ROBLOX_TOKEN", "").strip()
        if override:
            return override
        path = self._token_file()
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
            token = str(data.get("token") or "").strip()
            if token:
                return token
        except (OSError, ValueError):
            pass
        token = secrets.token_urlsafe(24)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(
            json.dumps({"token": token}, indent=2) + "\n",
            encoding="utf-8",
        )
        return token

    def token(self) -> str:
        if not self._token:
            self._token = self._load_token()
        return self._token

    def studio_status(self) -> dict[str, Any]:
        executable = find_studio()
        installed = plugin_path()
        return {
            "studio_installed": executable is not None,
            "studio_path": str(executable) if executable else "",
            "plugin_installed": installed.is_file(),
            "plugin_path": str(installed),
            "plugin_version": PLUGIN_VERSION,
            "protocol": PROTOCOL_VERSION,
        }

    def install_plugin(self) -> dict[str, Any]:
        target = plugin_path()
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(_plugin_source(self.token()), encoding="utf-8")
        return {
            "ok": True,
            "path": str(target),
            "version": PLUGIN_VERSION,
            "protocol": PROTOCOL_VERSION,
            "message": "Плагин установлен. Перезапусти Roblox Studio и включи HTTP-запросы.",
        }

    def _purge_expired_locked(self) -> None:
        now = time.monotonic()
        while self._queue and float(self._queue[0].get("_expires", 0)) <= now:
            row = self._queue.popleft()
            command_id = str(row.get("id") or "")
            self._pending.pop(command_id, None)
            result = {
                "id": command_id,
                "ok": False,
                "result": "",
                "error": "команда истекла: Studio не ответил вовремя",
            }
            self._results[command_id] = result
            self._last_error = result["error"]
        while len(self._results) > RESULT_LIMIT:
            self._results.popitem(last=False)

    def status(self) -> dict[str, Any]:
        with self._lock:
            self._purge_expired_locked()
            age = time.monotonic() - self._last_seen if self._last_seen else 9999
            return {
                "connected": age < 6,
                "last_seen_seconds": round(age, 1) if self._last_seen else None,
                "plugin_version": self._plugin_version,
                "protocol": self._plugin_protocol,
                "pending": len(self._queue),
                "last_error": self._last_error,
                "token_configured": bool(self.token()),
                "capabilities": sorted(COMMANDS),
                "recent_events": list(self._events)[-5:],
                **self.studio_status(),
            }

    def enqueue(self, command: dict[str, Any]) -> dict[str, Any]:
        payload = dict(command or {})
        kind = str(payload.get("type") or "").strip()
        payload["type"] = kind
        _validate_command(payload)
        command_id = "rbx_" + secrets.token_hex(8)
        now = time.monotonic()
        row = {**payload, "id": command_id, "_created": now, "_expires": now + COMMAND_TTL}
        with self._lock:
            if len(self._queue) >= self._queue.maxlen:
                dropped = self._queue.popleft()
                dropped_id = str(dropped.get("id") or "")
                self._pending.pop(dropped_id, None)
                self._results[dropped_id] = {
                    "id": dropped_id,
                    "ok": False,
                    "result": "",
                    "error": "очередь переполнена",
                }
            self._queue.append(row)
            self._pending[command_id] = row
        return {"ok": True, "id": command_id, "command": row}

    def _public(self, row: dict[str, Any]) -> dict[str, Any]:
        return {key: value for key, value in row.items() if not key.startswith("_")}

    def next_command(self, token: str) -> dict[str, Any]:
        if token != self.token():
            raise PermissionError("bad bridge token")
        with self._lock:
            self._purge_expired_locked()
            self._last_seen = time.monotonic()
            if not self._queue:
                return {
                    "command": None,
                    "protocol": PROTOCOL_VERSION,
                    "capabilities": sorted(COMMANDS),
                }
            command = self._queue.popleft()
            return {
                "command": self._public(command),
                "protocol": PROTOCOL_VERSION,
                "capabilities": sorted(COMMANDS),
            }

    def complete(self, token: str, payload: dict[str, Any]) -> dict[str, Any]:
        if token != self.token():
            raise PermissionError("bad bridge token")
        command_id = str(payload.get("id") or "")
        with self._lock:
            self._last_seen = time.monotonic()
            self._plugin_version = str(payload.get("plugin_version") or "")[:80]
            self._plugin_protocol = int(payload.get("protocol") or 0)
            self._pending.pop(command_id, None)
            result = {
                "id": command_id,
                "ok": bool(payload.get("ok")),
                "result": str(payload.get("result") or "")[:8000],
                "error": str(payload.get("error") or "")[:4000],
            }
            self._results[command_id] = result
            while len(self._results) > RESULT_LIMIT:
                self._results.popitem(last=False)
            if not result["ok"]:
                self._last_error = result["error"]
            return result

    def record_event(self, token: str, payload: dict[str, Any]) -> dict[str, Any]:
        if token != self.token():
            raise PermissionError("bad bridge token")
        event = {
            "kind": str(payload.get("kind") or "event")[:80],
            "ok": bool(payload.get("ok")),
            "result": str(payload.get("result") or "")[:4000],
            "plugin_version": str(payload.get("plugin_version") or "")[:80],
            "at": time.time(),
        }
        with self._lock:
            self._last_seen = time.monotonic()
            self._events.append(event)
        return {"ok": True, "event": event}

    def result(self, command_id: str) -> dict[str, Any] | None:
        with self._lock:
            return self._results.get(command_id)

    def launch_studio(self, place_path: str | None = None) -> dict[str, Any]:
        executable = find_studio()
        if executable is None:
            raise ValueError("Roblox Studio не найден в этой системе")
        args = [str(executable)]
        if place_path:
            place = Path(place_path).expanduser().resolve()
            if not place.is_file():
                raise ValueError(f"place file not found: {place}")
            if place.suffix.lower() not in {".rbxl", ".rbxlx"}:
                raise ValueError("place file must be .rbxl or .rbxlx")
            args.extend(["--task", "EditFile", "--localPlaceFile", str(place)])
        else:
            args.extend(["--task", "EditFile"])
        process = subprocess.Popen(
            args,
            cwd=str(executable.parent),
            close_fds=True,
        )
        return {
            "ok": True,
            "pid": process.pid,
            "studio": str(executable),
            "place": str(place_path) if place_path else "",
        }


